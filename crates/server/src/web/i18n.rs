pub fn a(lang: Lang) -> &'static A {
    match lang {
        Lang::En => &A_EN,
        Lang::Nl => &A_NL,
    }
}

impl A {
    /// A generic error by its key (set by `WebError` from a domain error).
    pub fn generic(&self, key: &str) -> Option<&'static str> {
        Some(match key {
            "not_found" => self.err_not_found,
            "read_only" => self.err_read_only,
            "name_taken" => self.err_name_taken,
            "bad_name" => self.err_bad_name,
            "server" => self.err_server,
            "admin_only" => self.err_admin_only,
            _ => return None,
        })
    }
}

/// A subscription error (fixed English sentences from `server::feeds`,
/// stored as written) in the reader's language. Unknown text passes through.
pub fn feed_error(lang: Lang, msg: &str) -> String {
    if lang == Lang::En {
        return msg.to_string();
    }
    const NL: [(&str, &str); 15] = [
        ("That is not a web address.", "Dat is geen webadres."),
        ("Use an https:// (or webcal://) address.", "Gebruik een https://- (of webcal://-)adres."),
        (
            "The address must not contain a user name or password.",
            "Het adres mag geen gebruikersnaam of wachtwoord bevatten.",
        ),
        ("The address's host name does not resolve.", "De hostnaam van het adres bestaat niet."),
        (
            "That address points into a private network, which this server does not fetch from.",
            "Dat adres wijst naar een privénetwerk; deze server haalt daar niets op.",
        ),
        ("The address did not answer in time.", "Het adres antwoordde niet op tijd."),
        ("Could not connect to the address.", "Kon geen verbinding maken met het adres."),
        ("The address redirected somewhere unusable.", "Het adres stuurde door naar iets onbruikbaars."),
        ("The address redirected too many times.", "Het adres stuurde te vaak door."),
        ("The feed is larger than 10 MiB.", "De feed is groter dan 10 MiB."),
        ("The download broke off.", "De download brak af."),
        ("The feed is not UTF-8 text.", "De feed is geen UTF-8-tekst."),
        ("The address does not serve an iCalendar (.ics) feed.", "Het adres levert geen iCalendar-feed (.ics)."),
        (
            "The feed has no events; the last good copy is kept.",
            "De feed heeft geen afspraken; de laatste goede kopie blijft staan.",
        ),
        ("The feed has no events.", "De feed heeft geen afspraken."),
    ];
    if let Some((_, nl)) = NL.iter().find(|(en, _)| *en == msg) {
        return nl.to_string();
    }
    if let Some(code) = msg.strip_prefix("The address answered with HTTP ").and_then(|r| r.strip_suffix('.')) {
        return format!("Het adres antwoordde met HTTP {code}.");
    }
    if msg.starts_with("Entry ") && msg.ends_with("the last good copy is kept.") {
        return "Een afspraak in de feed is onleesbaar; de laatste goede kopie blijft staan.".to_string();
    }
    msg.to_string()
}

#[cfg(test)]
mod tests {
    use super::*;
    use axum::http::HeaderValue;

    #[test]
    fn setting_then_browser_then_english() {
        let mut h = HeaderMap::new();
        assert_eq!(lang(None, &h), Lang::En);
        h.insert(ACCEPT_LANGUAGE, HeaderValue::from_static("nl-NL,nl;q=0.9,en;q=0.8"));
        assert_eq!(lang(None, &h), Lang::Nl);
        assert_eq!(lang(Some("en"), &h), Lang::En);
        h.insert(ACCEPT_LANGUAGE, HeaderValue::from_static("de-DE,de;q=0.9,en-GB;q=0.8,nl;q=0.5"));
        assert_eq!(lang(None, &h), Lang::En, "the first one we have");
        assert_eq!(lang(Some("nl"), &HeaderMap::new()), Lang::Nl);
    }
}
