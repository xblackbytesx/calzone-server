#[cfg(test)]
mod tests {
    use super::*;
    use axum::http::HeaderValue;

    #[test]
    fn setting_then_browser_then_english() {
        let mut h = HeaderMap::new();
        assert_eq!(lang(None, &h), Lang::En);
        h.insert(ACCEPT_LANGUAGE, HeaderValue::from_static("nl-NL,nl;q=0.9,en;q=0.8"));
        assert_eq!(lang(None, &h), Lang::Nl);
        assert_eq!(lang(Some("en"), &h), Lang::En);
        h.insert(ACCEPT_LANGUAGE, HeaderValue::from_static("de-DE,de;q=0.9,en-GB;q=0.8,nl;q=0.5"));
        assert_eq!(lang(None, &h), Lang::En, "the first one we have");
        assert_eq!(lang(Some("nl"), &HeaderMap::new()), Lang::Nl);
    }
}
