//! Languages (decision 35): which one a person gets (their setting, else
//! the browser's `Accept-Language`, else English), and every string the
//! translated pages show, one struct per language. Both languages fill the
//! same struct, so a missing translation does not compile. The calendar
//! script gets the same strings as JSON in a data attribute.

use axum::http::HeaderMap;
use axum::http::header::ACCEPT_LANGUAGE;
use calzone_core::quickadd::Lang;
use serde::Serialize;

/// The person's language: `setting` (`en`/`nl`) wins over the browser.
pub fn lang(setting: Option<&str>, headers: &HeaderMap) -> Lang {
    match setting {
        Some("nl") => return Lang::Nl,
        Some("en") => return Lang::En,
        _ => {}
    }
    let accept = headers.get(ACCEPT_LANGUAGE).and_then(|v| v.to_str().ok()).unwrap_or("");
    // The first language the browser lists that we have.
    for part in accept.split(',') {
        let tag = part.split(';').next().unwrap_or("").trim().to_ascii_lowercase();
        if tag.starts_with("nl") {
            return Lang::Nl;
        }
        if tag.starts_with("en") {
            return Lang::En;
        }
    }
    Lang::En
}

/// `en` or `nl`, for `<html lang>` and the grid's date formatting.
pub fn code(lang: Lang) -> &'static str {
    match lang {
        Lang::En => "en",
        Lang::Nl => "nl",
    }
}

/// A BCP 47 locale for `Intl` in the browser (day and month names).
pub fn locale(lang: Lang) -> &'static str {
    match lang {
        Lang::En => "en-GB",
        Lang::Nl => "nl-NL",
    }
}

pub fn t(lang: Lang) -> &'static T {
    match lang {
        Lang::En => &EN,
        Lang::Nl => &NL,
    }
}

